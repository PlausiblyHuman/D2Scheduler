const fs = require('fs'), os = require('os'), path = require('path'), cp = require('child_process');
let fail = 0;
const ok = (label, cond) => { console.log((cond ? 'PASS ' : 'FAIL ') + label); if (!cond) fail++; };
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mc-'));
const tgt = path.join(dir, 'target.json'), cap = path.join(dir, 'cap.json');
fs.writeFileSync(tgt, JSON.stringify({ jobs: [{ id: 'mine' }], cal: [1, 2] }, null, 1));
fs.writeFileSync(cap, JSON.stringify({ spt: [1, 2, 3], tpt: [4], trades: [5, 6], jobs: [{ id: 'theirs' }] }, null, 1));
const run = (...keys) => cp.spawnSync(process.execPath, [path.join(__dirname, 'merge-capture.js'), cap, tgt, ...keys], { encoding: 'utf8' });
const r = run('spt', 'tpt', 'trades');
ok('merge exits 0', r.status === 0);
ok('row counts printed', /spt: 3 rows/.test(r.stdout) && /tpt: 1 rows/.test(r.stdout) && /trades: 2 rows/.test(r.stdout));
const raw = fs.readFileSync(tgt, 'utf8'), t = JSON.parse(raw);
ok('target gained spt, tpt, trades', t.spt.length === 3 && t.tpt.length === 1 && t.trades.length === 2);
ok('target kept its own jobs', t.jobs.length === 1 && t.jobs[0].id === 'mine');
ok('target kept cal', t.cal.length === 2);
ok('formatting is stringify(d, null, 1)', raw === JSON.stringify(t, null, 1));
const before = fs.readFileSync(tgt, 'utf8');
const r2 = run('spt', 'nope');
ok('missing key exits 1', r2.status === 1);
ok('missing key leaves target unchanged', fs.readFileSync(tgt, 'utf8') === before);
fs.rmSync(dir, { recursive: true, force: true });
console.log(fail ? fail + ' FAILED' : 'all passed');
process.exit(fail ? 1 : 0);
