#!/usr/bin/env python3
"""Export live Power Automate flow definitions to flows/exports/.

WHY THIS EXISTS AS A SCRIPT: CLAUDE.md has documented this recipe since
2026-09-05, but the script itself was never committed, so exports were
regenerated by hand and drifted. A content audit on 2026-09-08b found 4 of 11
exports behind live, one of them missing an entire failure path -- restoring
that flow from its committed export would have silently deleted the fix.

TWO RULES, both learned the hard way:

  * The TOKEN comes from `az`; the RESPONSE must not. Piping `az rest` to a
    file on Windows silently DROPS characters outside cp1252 -- U+2192, U+26A0
    and U+2013 vanish rather than becoming mojibake, and PYTHONIOENCODING does
    not fix it. Characters that ARE in cp1252 survive, which makes the loss
    look selective and easy to miss. We fetch over urllib and write with an
    explicit encoding we control.

  * Compare exports by CONTENT, never by filename date. Same-day is not the
    same as after-the-last-change.

Usage:  python flows/scripts/export-flows.py [name-substring ...]
        (no args = every D2 flow; 'Generate estimate' is always excluded --
        it belongs to a separate estimator workload.)
"""
import json, re, shutil, subprocess, sys, urllib.request
from datetime import date
from pathlib import Path

ENV = "2710a01b-6cfa-e820-b338-2286f2649300"
TENANT = "f24d9b39-6a71-4f4e-a376-03b6f61c97e4"
OUT = Path(__file__).resolve().parents[1] / "exports"

def sh(*a):
    # On Windows `az` is az.cmd -- subprocess will not find it without resolving
    # the real executable first, and fails with a bare WinError 2.
    exe = shutil.which(a[0]) or a[0]
    return subprocess.run([exe, *a[1:]], capture_output=True, text=True).stdout.strip()

def assert_tenant():
    got = sh("az", "account", "show", "--query", "tenantId", "-o", "tsv")
    if got != TENANT:
        sys.exit(f"ABORT: az is on tenant {got!r}, expected D2 ({TENANT}). "
                 "An empty or wrong listing here has misled this project four times.")
    print(f"tenant CONFIRMED  {sh('az','account','show','--query','user.name','-o','tsv')}")

def get(url, tok):
    req = urllib.request.Request(url, headers={"Authorization": "Bearer " + tok})
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read().decode("utf-8"))   # explicit, never the console's idea of encoding

def slug(name):
    return re.sub(r"-+", "-", re.sub(r"[^A-Za-z0-9]+", "-", name)).strip("-")

def main():
    assert_tenant()
    tok = sh("az", "account", "get-access-token", "--resource",
             "https://service.flow.microsoft.com/", "--query", "accessToken", "-o", "tsv")
    if not tok:
        sys.exit("ABORT: no Flow token from az.")
    wanted = [a.lower() for a in sys.argv[1:]]
    url = (f"https://api.flow.microsoft.com/providers/Microsoft.ProcessSimple"
           f"/environments/{ENV}/flows?api-version=2016-11-01")
    flows = get(url, tok).get("value", [])
    OUT.mkdir(parents=True, exist_ok=True)
    stamp = date.today().isoformat()
    for f in flows:
        disp = f.get("properties", {}).get("displayName", "")
        if disp == "Generate estimate":
            continue
        if wanted and not any(w in disp.lower() for w in wanted):
            continue
        full = get(url.split("/flows?")[0] + f"/flows/{f['name']}?api-version=2016-11-01", tok)
        p = full.get("properties", {})
        doc = {
            "flowId": f["name"],
            "displayName": disp,
            "workflowEntityId": p.get("workflowEntityId"),
            "state": p.get("state"),
            "lastModifiedTime": p.get("lastModifiedTime"),
            "connectionReferences": p.get("connectionReferences"),
            "definition": p.get("definition"),
        }
        path = OUT / f"{slug(disp)}-{stamp}.json"
        path.write_text(json.dumps(doc, indent=1, ensure_ascii=False), encoding="utf-8")
        # Verify by reading back, not by the write returning.
        back = json.loads(path.read_text(encoding="utf-8"))
        ok = back["definition"] == doc["definition"]
        print(f"  {'ok ' if ok else 'MISMATCH'} {path.name}  ({p.get('state')}, "
              f"modified {p.get('lastModifiedTime')})")

main()
